#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE atrium_migrator WITH LOGIN SUPERUSER PASSWORD '${MIGRATE_PASSWORD}';
CREATE ROLE atrium_app WITH LOGIN NOSUPERUSER NOBYPASSRLS PASSWORD '${APP_PASSWORD}';
CREATE ROLE atrium_worker WITH LOGIN NOSUPERUSER BYPASSRLS PASSWORD '${WORKER_PASSWORD}';
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO atrium_app, atrium_worker, atrium_migrator;
SQL
